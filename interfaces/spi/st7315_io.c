/**
  * @brief  Assert chip select (CS low).
  * @param  pio : Pointer to io interface object.
  * @retval error status.
  */
int32_t st7315_io_select(st7315_io_t *pio)
{
  HAL_GPIO_WritePin(pio->cs_port, pio->cs_pin, HAL_GPIO_PIN_RESET);
  /*  Verify if the CS pin is indeed LOW */
  for (uint8_t t = 0U; t < ST7315_GPIO_MAX_CHECK_COUNT; t++)
  {
    if (HAL_GPIO_ReadPin(pio->cs_port, pio->cs_pin) == HAL_GPIO_PIN_RESET)
    {
      return 0;
    }
  }

  return -1;
}

/**
  * @brief  De-assert chip select (CS high).
  * @param  pio : Pointer to io interface object.
  * @retval error status.
  */
int32_t st7315_io_deselect(st7315_io_t *pio)
{
  HAL_GPIO_WritePin(pio->cs_port, pio->cs_pin, HAL_GPIO_PIN_SET);
  /*  Verify if the CS pin is indeed HIGH */
  for (uint8_t t = 0U; t < ST7315_GPIO_MAX_CHECK_COUNT; t++)
  {
    if (HAL_GPIO_ReadPin(pio->cs_port, pio->cs_pin) == HAL_GPIO_PIN_SET)
    {
      return 0;
    }
  }

  return -1;
}

/**
  * @brief  Execute the hardware reset sequence for st7315.
  * @param  pio : Pointer to io interface object.
  * @retval error status.
  */
int32_t st7315_io_hw_init_sequence(st7315_io_t *pio)
{
  int32_t ret = -1;
  /* Power ON stabilization delay t>1ms */
  HAL_Delay(2);

  /* Assert RST (active low) t > 3us */
  HAL_GPIO_WritePin(pio->rst_port, pio->rst_pin, HAL_GPIO_PIN_RESET);
  for (uint8_t t = 0U; t < ST7315_GPIO_MAX_CHECK_COUNT; t++)
  {
    if (HAL_GPIO_ReadPin(pio->rst_port, pio->rst_pin) == HAL_GPIO_PIN_RESET)
    {
      ret = 0;
      break;
    }
  }
  HAL_Delay(1);
  if (ret == 0)
  {
    /* De-assert RST and wait for the controller to be ready t > 3us */
    HAL_GPIO_WritePin(pio->rst_port, pio->rst_pin, HAL_GPIO_PIN_SET);
    for (uint8_t t = 0U; t < ST7315_GPIO_MAX_CHECK_COUNT; t++)
    {
      if (HAL_GPIO_ReadPin(pio->rst_port, pio->rst_pin) == HAL_GPIO_PIN_SET)
      {
        ret = 0;
        break;
      }
    }
    HAL_Delay(1);
  }

  return ret;
}

/**
  * @brief  Write a command byte to the ST7315 via SPI.
  * @param  pio : Pointer to io interface object.
  * @param  cmd : Command byte to send.
  * @retval error status.
  */
int32_t st7315_io_write_command(st7315_io_t *pio, uint8_t cmd)
{
  int32_t ret = -1;

  /* DC low: command mode */
  HAL_GPIO_WritePin(pio->dc_port, pio->dc_pin, HAL_GPIO_PIN_RESET);
  /* Verify the DC pin is indeed LOW before transmitting */
  for (uint8_t t = 0U; t < ST7315_GPIO_MAX_CHECK_COUNT; t++)
  {
    if (HAL_GPIO_ReadPin(pio->dc_port, pio->dc_pin) == HAL_GPIO_PIN_RESET)
    {
      ret = 0;
      break;
    }
  }

  if (ret == 0)
  {
    ret = st7315_io_select(pio);
    if (ret == 0)
    {
      ret = st7315_io_spi_write(pio, &cmd, 1U);
      if (st7315_io_deselect(pio) != 0)
      {
        ret = -1;
      }
    }
  }

  return ret;
}

/**
  * @brief  Write multiple data bytes to the ST7315 via SPI.
  * @param  pio   : Pointer to io interface object.
  * @param  pdata : Pointer to data buffer.
  * @param  size  : Number of bytes to write.
  * @retval error status.
  */
int32_t st7315_io_write_multiple_data(st7315_io_t *pio, uint8_t *pdata, uint32_t size)
{
  int32_t ret = -1;

  /* DC high: data mode */
  HAL_GPIO_WritePin(pio->dc_port, pio->dc_pin, HAL_GPIO_PIN_SET);
  for (uint8_t t = 0U; t < ST7315_GPIO_MAX_CHECK_COUNT; t++)
  {
    if (HAL_GPIO_ReadPin(pio->dc_port, pio->dc_pin) == HAL_GPIO_PIN_SET)
    {
      ret = 0;
      break;
    }
  }
  if (ret == 0)
  {
    if (st7315_io_select(pio) != 0)
    {
      ret = -1;
    }
    else
    {
      ret = st7315_io_spi_write(pio, pdata, size);
      if (st7315_io_deselect(pio) != 0)
      {
        ret = -1;
      }
    }
  }

  return ret;
}

/**
  * @brief  Transmit bytes over SPI.
  * @param  pio   : Pointer to io interface object.
  * @param  pdata : Pointer to data buffer.
  * @param  size  : Number of bytes to transmit.
  * @retval error status.
  */
static int32_t st7315_io_spi_write(st7315_io_t *pio, uint8_t *pdata, uint32_t size)
{
  if (HAL_SPI_Transmit(pio->phspi, pdata, (uint16_t)size, ST7315_SPI_TIMEOUT_VALUE) != HAL_OK)
  {
    return -1;
  }
  return 0;
}



